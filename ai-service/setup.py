"""
Quick setup helper: 
- Downloads a sample classroom video from a free source
- Logs into the backend to get an auth token
- Updates config.py with real centre_id and token

Run once before starting detector.py
"""

import requests
import json
import os

BACKEND = "http://localhost:3000/api/v1"
HEADERS = {"ngrok-skip-browser-warning": "true", "Content-Type": "application/json"}

print("=" * 60)
print("  SIH AI Detection Service — Setup Wizard")
print("=" * 60)

# 1. Login to get token
print("\n📡 Step 1: Login to backend to get auth token...")
email = input("Enter officer/admin email (default: officer@sih.gov.in): ").strip() or "officer@sih.gov.in"
password = input("Enter password (default: officer123): ").strip() or "officer123"

try:
    resp = requests.post(f"{BACKEND}/auth/login", json={"email": email, "password": password}, headers=HEADERS)
    if resp.status_code == 200:
        data = resp.json()
        token = data.get("accessToken") or data.get("token") or ""
        user = data.get("user", {})
        centre_id = user.get("centreId", "")
        print(f"✅ Logged in as: {user.get('fullName', email)} ({user.get('role', '')})")
        print(f"   Centre ID: {centre_id or '(admin - no centre)'}")
        print(f"   Token: {token[:30]}...")
    else:
        print(f"❌ Login failed: {resp.text}")
        token = ""
        centre_id = ""
except Exception as e:
    print(f"❌ Could not connect to backend: {e}")
    token = ""
    centre_id = ""

# 2. Ask for video source
print("\n🎥 Step 2: Configure video source...")
print("  0 = laptop webcam")
print("  1 = external USB webcam")
print("  path = video file (e.g. C:\\Videos\\class.mp4)")
video_source = input("Enter video source (default: 0 for webcam): ").strip() or "0"

# 3. Write config.py
print("\n💾 Step 3: Updating config.py...")
config_content = f'''"""
Configuration for AI Detection Service
SIH26245 - AI-Based Real-Time Monitoring of Training Centres
Auto-generated by setup.py
"""

import os

# ─── Backend Connection ───────────────────────────────────────
BACKEND_URL = os.getenv("BACKEND_URL", "http://localhost:3000/api/v1")

# Auth token (auto-generated by setup.py)
AUTH_TOKEN = os.getenv("AUTH_TOKEN", "{token}")

# ─── Centre & Camera Info ─────────────────────────────────────
CENTRE_ID = os.getenv("CENTRE_ID", "{centre_id}")
CAMERA_ID = os.getenv("CAMERA_ID", "webcam-001")

# ─── Video Source ─────────────────────────────────────────────
VIDEO_SOURCE = os.getenv("VIDEO_SOURCE", "{video_source}")

# ─── Detection Settings ──────────────────────────────────────
CONFIDENCE_THRESHOLD = 0.4
REPORT_INTERVAL = 10   # seconds between backend reports
MODEL_NAME = "yolov8n.pt"

# ─── Stream Server ────────────────────────────────────────────
STREAM_HOST = "0.0.0.0"
STREAM_PORT = 8000
'''

with open("config.py", "w") as f:
    f.write(config_content)

print("✅ config.py updated!")

print("\n" + "=" * 60)
print("✅ Setup complete! Now run:")
print("   python detector.py")
print()
print("📺 Live stream:  http://localhost:8000/video_feed")
print("📊 Status:       http://localhost:8000/status")
print("=" * 60)
